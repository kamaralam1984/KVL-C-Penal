"""Customer database provisioning (MariaDB/MySQL and PostgreSQL) through allow-listed client binaries.

Safety model:
- Identifiers must match ^[a-z][a-z0-9_]{2,31}$ AND the panel-managed naming pattern (so 'root', 'postgres', 'mysql' can never be targeted).
- Passwords must match ^[A-Za-z0-9_-]{24,64}$ (generated by the panel) and are additionally quoted/escaped.
- SQL goes into a 0600 script file inside the sandbox (never argv, never a shell); the admin credential comes from a defaults file /
  environment variable configured on the server and is never read from job params or returned.
- Grants are limited to the single customer database; no GRANT OPTION, no global privileges.
- Results contain no SQL text and no secrets; error output is redacted with the password.
Admin configuration (all optional; absence => status not_configured):
  KVL_MYSQL_DEFAULTS_FILE         path to a mysql defaults-extra-file with the admin [client] credentials
  KVL_PG_ADMIN_USER / KVL_PG_ADMIN_PASSWORD / KVL_PG_HOST / KVL_PG_PORT
(or ctx.extra["db_admin"] = {"mariadb": {"defaults_file": ...}, "postgresql": {"user", "password", "host", "port"}}).
"""
import hashlib
import os
import re
import secrets
from pathlib import Path
from typing import Literal

from pydantic import BaseModel, ConfigDict, Field, field_validator

from kvl_agent.context import OpContext, allow_binary
from kvl_agent.redact import redact_text
from kvl_agent.registry import operation

allow_binary("mysql", "mysqldump", "psql", "pg_dump")

IDENT_RE = re.compile(r"^[a-z][a-z0-9_]{2,31}$")
MANAGED_DB_RE = re.compile(r"^[a-z][a-z0-9]{1,13}_[a-f0-9]{6}$")
MANAGED_USER_RE = re.compile(r"^[a-z][a-z0-9]{1,13}_[a-f0-9]{6}_[a-z][a-z0-9]{0,5}$")
PASSWORD_RE = re.compile(r"^[A-Za-z0-9_-]{24,64}$")
ARTIFACT_RE = re.compile(r"^[a-z][a-z0-9_]{2,31}-\d{8}T\d{6}Z\.sql$")
SAFE_PATH = re.compile(r"^[A-Za-z0-9_./-]+$")
Engine = Literal["mariadb", "postgresql"]

MYSQL_RW = "SELECT, INSERT, UPDATE, DELETE, CREATE, DROP, INDEX, ALTER, REFERENCES, CREATE TEMPORARY TABLES, LOCK TABLES"
MYSQL_RO = "SELECT, SHOW VIEW"


def _ident(v: str) -> str:
    if not IDENT_RE.fullmatch(v):
        raise ValueError("identifier must match ^[a-z][a-z0-9_]{2,31}$")
    return v


def _db(v: str) -> str:
    _ident(v)
    if not MANAGED_DB_RE.fullmatch(v):
        raise ValueError("not a panel-managed database name")
    return v


def _user(v: str) -> str:
    _ident(v)
    if not MANAGED_USER_RE.fullmatch(v):
        raise ValueError("not a panel-managed user name")
    return v


class _Strict(BaseModel):
    model_config = ConfigDict(extra="forbid")


class DbRef(_Strict):
    engine: Engine
    db_name: str
    _v = field_validator("db_name")(_db)


class UserSpec(DbRef):
    username: str
    privilege: Literal["readwrite", "readonly"] = "readwrite"
    password: str = Field(pattern=PASSWORD_RE.pattern)
    _u = field_validator("username")(_user)


class Provision(UserSpec):
    pass


class CreateUser(UserSpec):
    pass


class RotatePassword(_Strict):
    engine: Engine
    username: str
    password: str = Field(pattern=PASSWORD_RE.pattern)
    _u = field_validator("username")(_user)


class DropUser(_Strict):
    engine: Engine
    username: str
    _u = field_validator("username")(_user)


class Drop(DbRef):
    confirm_name: str
    users: list[str] = Field(default_factory=list, max_length=20)
    _u = field_validator("users")(lambda v: [_user(x) for x in v])
    _c = field_validator("confirm_name")(_db)


class Size(DbRef):
    pass


class Dump(DbRef):
    artifact: str = Field(pattern=ARTIFACT_RE.pattern)


class Restore(DbRef):
    artifact: str = Field(pattern=ARTIFACT_RE.pattern)
    checksum: str = Field(pattern=r"^[a-f0-9]{64}$")


class DetectEngines(_Strict):
    pass


# --------------------------------------------------------------------------- SQL builders (pure; unit-tested)
def my_ident(x: str) -> str:
    assert IDENT_RE.fullmatch(x)
    return f"`{x}`"


def pg_ident(x: str) -> str:
    assert IDENT_RE.fullmatch(x)
    return f'"{x}"'


def my_lit(s: str) -> str:
    return "'" + s.replace("\\", "\\\\").replace("'", "''") + "'"


def pg_lit(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"  # standard_conforming_strings=on: backslash is literal


def _grant_target(db: str) -> str:
    """MySQL treats _ and % in database-level GRANT targets as wildcards; escape so the grant cannot match sibling databases."""
    return "`" + db.replace("_", "\\_") + "`.*"


def mysql_create_user(db: str, user: str, pw: str, privilege: str) -> list[str]:
    privs = MYSQL_RW if privilege == "readwrite" else MYSQL_RO
    acct = f"{my_lit(user)}@'localhost'"
    return [f"CREATE USER {acct} IDENTIFIED BY {my_lit(pw)}", f"GRANT {privs} ON {_grant_target(db)} TO {acct}"]


def mysql_provision(db: str, user: str, pw: str, privilege: str) -> list[str]:
    return [f"CREATE DATABASE {my_ident(db)} CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci", *mysql_create_user(db, user, pw, privilege), "FLUSH PRIVILEGES"]


def pg_role(user: str, pw: str) -> str:
    return f"CREATE ROLE {pg_ident(user)} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOINHERIT PASSWORD {pg_lit(pw)}"


def pg_provision(db: str, user: str, pw: str, privilege: str) -> list[str]:
    return [
        pg_role(user, pw),
        f"CREATE DATABASE {pg_ident(db)} OWNER {pg_ident(user)} ENCODING 'UTF8' TEMPLATE template0",
        f"REVOKE ALL ON DATABASE {pg_ident(db)} FROM PUBLIC",
        f"GRANT CONNECT ON DATABASE {pg_ident(db)} TO {pg_ident(user)}",
    ]


def pg_create_user(db: str, user: str, pw: str, privilege: str) -> list[str]:
    owner = f"{db}_app"
    u, d = pg_ident(user), pg_ident(db)
    stmts = [pg_role(user, pw), f"GRANT CONNECT ON DATABASE {d} TO {u}", f"\\connect {d}", f"GRANT USAGE ON SCHEMA public TO {u}"]
    if privilege == "readwrite":
        stmts += [f"GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO {u}", f"GRANT USAGE, SELECT, UPDATE ON ALL SEQUENCES IN SCHEMA public TO {u}",
                  f"ALTER DEFAULT PRIVILEGES FOR ROLE {pg_ident(owner)} IN SCHEMA public GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO {u}",
                  f"ALTER DEFAULT PRIVILEGES FOR ROLE {pg_ident(owner)} IN SCHEMA public GRANT USAGE, SELECT, UPDATE ON SEQUENCES TO {u}"]
    else:
        stmts += [f"GRANT SELECT ON ALL TABLES IN SCHEMA public TO {u}", f"ALTER DEFAULT PRIVILEGES FOR ROLE {pg_ident(owner)} IN SCHEMA public GRANT SELECT ON TABLES TO {u}"]
    return stmts


def provision_sql(engine: str, db: str, user: str, pw: str, privilege: str) -> list[str]:
    return mysql_provision(db, user, pw, privilege) if engine == "mariadb" else pg_provision(db, user, pw, privilege)


def create_user_sql(engine: str, db: str, user: str, pw: str, privilege: str) -> list[str]:
    return [*mysql_create_user(db, user, pw, privilege), "FLUSH PRIVILEGES"] if engine == "mariadb" else pg_create_user(db, user, pw, privilege)


def rotate_sql(engine: str, user: str, pw: str) -> list[str]:
    if engine == "mariadb":
        return [f"ALTER USER {my_lit(user)}@'localhost' IDENTIFIED BY {my_lit(pw)}", "FLUSH PRIVILEGES"]
    return [f"ALTER ROLE {pg_ident(user)} PASSWORD {pg_lit(pw)}"]


def drop_user_sql(engine: str, user: str) -> list[str]:
    if engine == "mariadb":
        return [f"DROP USER IF EXISTS {my_lit(user)}@'localhost'"]
    return [f"DROP ROLE IF EXISTS {pg_ident(user)}"]


def drop_sql(engine: str, db: str, users: list[str]) -> list[str]:
    if engine == "mariadb":
        return [f"DROP DATABASE IF EXISTS {my_ident(db)}", *[s for u in users for s in drop_user_sql(engine, u)], "FLUSH PRIVILEGES"]
    return [f"SELECT pg_terminate_backend(pid) FROM pg_stat_activity WHERE datname = {pg_lit(db)} AND pid <> pg_backend_pid()", f"DROP DATABASE IF EXISTS {pg_ident(db)}",
            *[s for u in users for s in drop_user_sql(engine, u)]]


# --------------------------------------------------------------------------- execution
def _admin(ctx: OpContext, engine: str) -> dict | None:
    cfg = (ctx.extra.get("db_admin") or {}).get(engine)
    if cfg:
        return cfg
    if engine == "mariadb":
        f = os.environ.get("KVL_MYSQL_DEFAULTS_FILE")
        return {"defaults_file": f} if f else None
    user, pw = os.environ.get("KVL_PG_ADMIN_USER"), os.environ.get("KVL_PG_ADMIN_PASSWORD")
    if not user:
        return None
    return {"user": user, "password": pw or "", "host": os.environ.get("KVL_PG_HOST", "127.0.0.1"), "port": os.environ.get("KVL_PG_PORT", "5432")}


def _client(engine: str) -> str:
    return "mysql" if engine == "mariadb" else "psql"


def _not_configured(ctx: OpContext, engine: str) -> dict | None:
    if not ctx.which(_client(engine)):
        return {"ok": False, "status": "not_configured", "message": f"The {_client(engine)} client is not installed on this server; nothing was changed."}
    if _admin(ctx, engine) is None:
        return {"ok": False, "status": "not_configured", "message": "Database administration is not configured for the agent on this server; nothing was changed."}
    return None


def _script_path(ctx: OpContext) -> Path:
    d = ctx.path("tmp", "db")
    d.mkdir(parents=True, exist_ok=True)
    os.chmod(d, 0o700)
    return d / f"{secrets.token_hex(8)}.sql"


def _run_sql(ctx: OpContext, engine: str, statements: list[str], *, secret: str | None = None, database: str | None = None, capture: bool = False):
    """Run statements via a 0600 script. Returns (ok, stdout, error_text). The script is always removed."""
    script = _script_path(ctx)
    if not SAFE_PATH.fullmatch(str(script)):
        return False, "", "Unsupported agent data directory path."
    fd = os.open(script, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
    with os.fdopen(fd, "w") as f:
        f.write(";\n".join(s for s in statements if not s.startswith("\\")) + ";\n" if engine == "mariadb" else "".join(s + "\n" if s.startswith("\\") else s + ";\n" for s in statements))
    try:
        cfg = _admin(ctx, engine)
        if engine == "mariadb":
            argv = ["mysql", f"--defaults-extra-file={cfg['defaults_file']}", "--batch", "--skip-column-names"]
            if database:
                argv += ["-D", database]
            argv += ["-e", f"source {script}"]
            env = {}
        else:
            argv = ["psql", "-X", "-q", "-A", "-t", "-v", "ON_ERROR_STOP=1", "-h", str(cfg["host"]), "-p", str(cfg["port"]), "-U", cfg["user"], "-d", database or "postgres", "-f", str(script)]
            env = {"PGPASSWORD": cfg.get("password", ""), "PGCONNECT_TIMEOUT": "10"}
        r = ctx.run(argv, timeout=120, env=env)
        extra = [secret, cfg.get("password") if engine == "postgresql" else None]
        err = redact_text((r.stderr or r.stdout)[-600:], [x for x in extra if x])
        return r.ok, r.stdout, err
    finally:
        try:
            script.unlink()
        except FileNotFoundError:
            pass


def _dry(statements: list[str], secret: str | None) -> dict:
    shown = [redact_text(s, [secret] if secret else None) for s in statements]
    return {"ok": True, "status": "dry_run", "statements": shown}


@operation("db.detect_engines", DetectEngines, timeout=60)
def detect_engines(_p: DetectEngines, ctx: OpContext) -> dict:
    engines: dict[str, str | None] = {"mariadb": None, "postgresql": None}
    if ctx.which("mysql") and _admin(ctx, "mariadb"):
        r = ctx.run(["mysql", "--version"], timeout=10)
        m = re.search(r"Distrib (\d{1,2}\.\d{1,2})", r.stdout) or re.search(r"Ver (\d{1,2}\.\d{1,2})", r.stdout)
        if r.ok and m:
            engines["mariadb"] = m.group(1)
    if ctx.which("psql") and _admin(ctx, "postgresql"):
        r = ctx.run(["psql", "--version"], timeout=10)
        m = re.search(r"(\d{1,2})(?:\.\d{1,2})?", r.stdout)
        if r.ok and m:
            engines["postgresql"] = m.group(1)
    return {"ok": True, "engines": engines}


@operation("db.provision", Provision, timeout=120)
def provision(p: Provision, ctx: OpContext) -> dict:
    stmts = provision_sql(p.engine, p.db_name, p.username, p.password, p.privilege)
    if ctx.dry_run:
        return _dry(stmts, p.password)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, _, err = _run_sql(ctx, p.engine, stmts, secret=p.password)
    if ok:
        return {"ok": True, "status": "provisioned", "database": p.db_name, "username": p.username}
    # Roll back anything that was half-created.
    cok, _, _ = _run_sql(ctx, p.engine, drop_sql(p.engine, p.db_name, [p.username]))
    return {"ok": False, "status": "provision_failed", "message": f"Provisioning failed: {err}", "cleaned_up": cok}


@operation("db.create_user", CreateUser, timeout=60)
def create_user(p: CreateUser, ctx: OpContext) -> dict:
    stmts = create_user_sql(p.engine, p.db_name, p.username, p.password, p.privilege)
    if ctx.dry_run:
        return _dry(stmts, p.password)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, _, err = _run_sql(ctx, p.engine, stmts, secret=p.password)
    if ok:
        return {"ok": True, "status": "user_created", "username": p.username}
    _run_sql(ctx, p.engine, drop_user_sql(p.engine, p.username))
    return {"ok": False, "status": "user_failed", "message": f"Could not create user: {err}", "cleaned_up": True}


@operation("db.rotate_password", RotatePassword, timeout=60)
def rotate_password(p: RotatePassword, ctx: OpContext) -> dict:
    stmts = rotate_sql(p.engine, p.username, p.password)
    if ctx.dry_run:
        return _dry(stmts, p.password)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, _, err = _run_sql(ctx, p.engine, stmts, secret=p.password)
    return {"ok": True, "status": "rotated", "username": p.username} if ok else {"ok": False, "status": "rotate_failed", "message": f"Rotation failed: {err}"}


@operation("db.drop_user", DropUser, timeout=60, destructive=True)
def drop_user(p: DropUser, ctx: OpContext) -> dict:
    stmts = drop_user_sql(p.engine, p.username)
    if ctx.dry_run:
        return _dry(stmts, None)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, _, err = _run_sql(ctx, p.engine, stmts)
    return {"ok": True, "status": "user_dropped"} if ok else {"ok": False, "status": "drop_failed", "message": err}


@operation("db.drop", Drop, timeout=120, destructive=True)
def drop(p: Drop, ctx: OpContext) -> dict:
    if p.confirm_name != p.db_name:
        return {"ok": False, "status": "confirmation_mismatch", "message": "confirm_name does not match db_name; nothing was dropped."}
    stmts = drop_sql(p.engine, p.db_name, p.users)
    if ctx.dry_run:
        return _dry(stmts, None)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, _, err = _run_sql(ctx, p.engine, stmts)
    return {"ok": True, "status": "dropped"} if ok else {"ok": False, "status": "drop_failed", "message": err}


@operation("db.size", Size, timeout=60)
def size(p: Size, ctx: OpContext) -> dict:
    if p.engine == "mariadb":
        stmts = [f"SELECT COALESCE(SUM(data_length + index_length), 0) FROM information_schema.tables WHERE table_schema = {my_lit(p.db_name)}"]
    else:
        stmts = [f"SELECT pg_database_size({pg_lit(p.db_name)})"]
    if ctx.dry_run:
        return _dry(stmts, None)
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    ok, out, err = _run_sql(ctx, p.engine, stmts)
    m = re.search(r"\d+", out or "")
    if not ok or not m:
        return {"ok": False, "status": "size_failed", "message": err or "Unexpected output."}
    return {"ok": True, "status": "size", "size_bytes": int(m.group(0))}


def _backup_path(ctx: OpContext, db: str, artifact: str) -> Path:
    if not artifact.startswith(db + "-"):
        raise ValueError("artifact does not belong to this database")
    return ctx.path("backups", "db", artifact)


def _sha256(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()


def _complete_marker(path: Path, engine: str) -> bool:
    with path.open("rb") as f:
        f.seek(0, os.SEEK_END)
        f.seek(max(0, f.tell() - 4096))
        tail = f.read().decode(errors="replace")
    return ("Dump completed" in tail) if engine == "mariadb" else ("PostgreSQL database dump complete" in tail)


@operation("db.dump", Dump, timeout=900)
def dump(p: Dump, ctx: OpContext) -> dict:
    try:
        out = _backup_path(ctx, p.db_name, p.artifact)
    except ValueError as e:
        return {"ok": False, "status": "rejected", "message": str(e)}
    if ctx.dry_run:
        return {"ok": True, "status": "dry_run", "would_write": f"backups/db/{p.artifact}"}
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    cfg = _admin(ctx, p.engine)
    if not ctx.which("mysqldump" if p.engine == "mariadb" else "pg_dump"):
        return {"ok": False, "status": "not_configured", "message": "The dump client is not installed on this server; nothing was changed."}
    if p.engine == "mariadb":
        argv = ["mysqldump", f"--defaults-extra-file={cfg['defaults_file']}", "--single-transaction", "--routines", "--triggers", "--no-tablespaces", f"--result-file={out}", p.db_name]
        env = {}
    else:
        argv = ["pg_dump", "-h", str(cfg["host"]), "-p", str(cfg["port"]), "-U", cfg["user"], "-d", p.db_name, "--no-owner", "--no-privileges", "--clean", "--if-exists", "-f", str(out)]
        env = {"PGPASSWORD": cfg.get("password", "")}
    out.parent.mkdir(parents=True, exist_ok=True)
    r = ctx.run(argv, timeout=850, env=env)
    if not r.ok or not out.exists() or out.stat().st_size == 0:
        out.unlink(missing_ok=True)
        return {"ok": False, "status": "dump_failed", "message": redact_text((r.stderr or "empty dump")[-500:])}
    os.chmod(out, 0o600)
    return {"ok": True, "status": "dumped", "artifact": p.artifact, "size_bytes": out.stat().st_size, "checksum": _sha256(out), "verified": _complete_marker(out, p.engine)}


@operation("db.restore", Restore, timeout=900, destructive=True)
def restore(p: Restore, ctx: OpContext) -> dict:
    try:
        src = _backup_path(ctx, p.db_name, p.artifact)
    except ValueError as e:
        return {"ok": False, "status": "rejected", "message": str(e)}
    if not src.exists():
        return {"ok": False, "status": "artifact_missing", "message": "The backup file is not on this server."}
    if _sha256(src) != p.checksum:
        return {"ok": False, "status": "integrity_failed", "message": "Backup checksum mismatch; the database was NOT modified."}
    if ctx.dry_run:
        return {"ok": True, "status": "dry_run", "verified": True}
    nc = _not_configured(ctx, p.engine)
    if nc:
        return nc
    if not SAFE_PATH.fullmatch(str(src)):
        return {"ok": False, "status": "rejected", "message": "Unsupported agent data directory path."}
    cfg = _admin(ctx, p.engine)
    if p.engine == "mariadb":
        argv = ["mysql", f"--defaults-extra-file={cfg['defaults_file']}", "--batch", "-D", p.db_name, "-e", f"source {src}"]
        env = {}
    else:
        argv = ["psql", "-X", "-q", "-v", "ON_ERROR_STOP=1", "-h", str(cfg["host"]), "-p", str(cfg["port"]), "-U", cfg["user"], "-d", p.db_name, "-f", str(src)]
        env = {"PGPASSWORD": cfg.get("password", "")}
    r = ctx.run(argv, timeout=850, env=env)
    if not r.ok:
        return {"ok": False, "status": "restore_failed", "message": redact_text((r.stderr or r.stdout)[-500:])}
    return {"ok": True, "status": "restored", "verified": True}
